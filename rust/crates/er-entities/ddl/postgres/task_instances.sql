CREATE TABLE IF NOT EXISTS public.task_instances (
  id text NOT NULL,
  org_id text NOT NULL REFERENCES orgs(id),
  job_id text NOT NULL REFERENCES jobs(id),
  task_id text NOT NULL,
  seq bigint NOT NULL,
  try_number bigint NOT NULL DEFAULT 1,
  live boolean,
  archived_reason text CHECK (archived_reason IN ('retry', 'cleared', 'restarted')),
  kind text NOT NULL DEFAULT 'pod' CHECK (kind IN ('pod', 'control')),
  state text NOT NULL DEFAULT 'none' CHECK (state IN ('none', 'scheduled', 'queued', 'running', 'up_for_retry', 'restarting', 'canceling', 'succeeded', 'skipped', 'failed', 'timed_out', 'upstream_failed', 'upstream_skipped', 'canceled')),
  trigger_rule text NOT NULL DEFAULT 'all_succeeded' CHECK (trigger_rule IN ('all_succeeded', 'all_terminal', 'any_failed')),
  upstream jsonb NOT NULL DEFAULT '[]'::jsonb,
  teardown boolean NOT NULL DEFAULT false,
  segment text,
  resource_class text CHECK (resource_class IN ('S', 'M', 'L')),
  next_resource_class text CHECK (next_resource_class IN ('S', 'M', 'L')),
  escalated_from text CHECK (escalated_from IN ('S', 'M')),
  max_tries bigint NOT NULL DEFAULT 0,
  launches bigint NOT NULL DEFAULT 0,
  max_launches bigint NOT NULL DEFAULT 3,
  not_before timestamptz,
  input jsonb,
  output jsonb,
  outcome text CHECK (outcome IN ('done', 'no_op')),
  exit_code bigint,
  termination_reason text,
  error_class text CHECK (error_class IN ('transient_io', 'lock_conflict', 'precondition', 'config', 'contradiction', 'non_convergence', 'data', 'internal', 'infrastructure', 'resources', 'timeout')),
  error_detail text,
  owner_epoch text,
  k8s_job_name text,
  pod_name text,
  pod_uid text,
  node_name text,
  image_digest text,
  snapshot_start bigint,
  snapshot_end bigint,
  counters jsonb,
  trace_context text,
  token_hash text,
  scheduled_at timestamptz,
  queued_at timestamptz,
  started_at timestamptz,
  heartbeat_at timestamptz,
  finished_at timestamptz,
  created_at timestamptz NOT NULL DEFAULT now(),
  updated_at timestamptz NOT NULL DEFAULT now(),
  PRIMARY KEY (id),
  UNIQUE (job_id, task_id, try_number)
);
CREATE INDEX IF NOT EXISTS task_instances_org_job ON public.task_instances (org_id, job_id);
CREATE UNIQUE INDEX IF NOT EXISTS task_instances_live ON public.task_instances (job_id, task_id) WHERE live IS TRUE;
CREATE UNIQUE INDEX IF NOT EXISTS task_instances_one_pod_per_org ON public.task_instances (org_id) WHERE live IS TRUE AND kind = 'pod' AND state IN ('queued','running','restarting','canceling');
CREATE INDEX IF NOT EXISTS task_instances_claimable ON public.task_instances (state, not_before, job_id, seq) WHERE live IS TRUE;
CREATE INDEX IF NOT EXISTS task_instances_heartbeat ON public.task_instances (heartbeat_at) WHERE live IS TRUE AND state = 'running';
