//! The ERD emitter: `docs/erd.md`, the entity-relationship diagram of every store.
//!
//! One Mermaid `erDiagram` per store, from the same authorities the rest of the
//! generator reads: the entity catalog for the Postgres control plane (whose
//! `references:` are real foreign keys), the drizzle snapshot for the frontend's
//! `erweb` schema, and the `er-schema` S5 registry for the lake. DuckLake enforces
//! `NOT NULL` and nothing else — no foreign key exists to read — so every lake
//! edge is *name-implied*: a relation whose columns contain another relation's
//! declared logical key is drawn referencing it, dotted, as a reading aid and
//! never as a constraint claim. An implied edge whose target is ambiguous
//! (several relations share the key) is dropped, not guessed.

use std::collections::{BTreeMap, BTreeSet};

use er_entity_spec::{Catalog, Entity, Store};
use er_schema::model::{Owner, TableSpec, all_specs};
use serde::Deserialize;

/// An ERD emission failure: the drizzle snapshot did not parse.
#[derive(Debug, thiserror::Error)]
pub enum ErdError {
    /// `frontend/drizzle/meta/<latest>_snapshot.json` is not the shape drizzle-kit
    /// writes (snapshot format 7).
    #[error("parsing the drizzle snapshot: {0}")]
    Snapshot(#[from] serde_json::Error),
}

/// Render `docs/erd.md`. `erweb_snapshot` is the latest drizzle snapshot's JSON
/// (the frontend's `erweb` schema); `None` omits that section.
pub fn emit_erd(catalog: &Catalog, erweb_snapshot: Option<&str>) -> Result<String, ErdError> {
    let mut out = String::from(
        "<!-- @generated by er-entity-gen — DO NOT EDIT. Regenerate with `er-entity gen`;\n\
         `er-entity verify` (CI) fails when this file is stale. -->\n\n\
         # Entity-relationship diagram\n\n\
         Every relation of every store, drawn from the schema authorities themselves: the\n\
         entity catalog (`entities/*/entity.yaml`) for the Postgres control plane, the\n\
         drizzle snapshot (`frontend/drizzle/meta/`) for the frontend's `erweb` schema, and\n\
         the `er-schema` S5 registry for the DuckLake lake. Attribute markers: `PK` the\n\
         primary/logical key, `FK` a declared foreign key, `UK` a unique index.\n",
    );

    control_plane_section(catalog, &mut out);
    if let Some(snapshot) = erweb_snapshot {
        erweb_section(snapshot, &mut out)?;
    }
    lake_section(catalog, &mut out);
    Ok(out)
}

/// Lowercase a store type for a Mermaid attribute, with no internal whitespace
/// (Mermaid's attribute grammar takes one word; parentheses and brackets are fine).
fn mermaid_type(store_type: &str) -> String {
    match store_type {
        "timestamp with time zone" => "timestamptz".to_string(),
        "double precision" => "double".to_string(),
        other => other.to_lowercase().replace(' ', "_"),
    }
}

/// `"in {a, b}"` — the attribute comment for a closed-domain column.
fn domain_comment(values: &BTreeSet<String>) -> String {
    let list: Vec<&str> = values.iter().map(String::as_str).collect();
    format!("\"in {{{}}}\"", list.join(", "))
}

/// One Mermaid attribute line: `type name PK, FK "comment"`.
fn attribute_line(
    out: &mut String,
    col_type: &str,
    name: &str,
    markers: &[&str],
    comment: Option<&str>,
) {
    out.push_str(&format!("        {} {}", mermaid_type(col_type), name));
    if !markers.is_empty() {
        out.push_str(&format!(" {}", markers.join(", ")));
    }
    if let Some(comment) = comment {
        out.push_str(&format!(" {comment}"));
    }
    out.push('\n');
}

// --------------------------------------------------------------------------- //
// the control plane — the entity catalog's `postgres` store
// --------------------------------------------------------------------------- //

fn control_plane_section(catalog: &Catalog, out: &mut String) {
    let entities = catalog.for_store(Store::Postgres);
    if entities.is_empty() {
        return;
    }
    out.push_str(
        "\n## Control plane — Postgres `public`\n\n\
         The erserver control database, provisioned at boot from the generated\n\
         `POSTGRES_BASELINE`. Every edge is a declared foreign key (`references:` in the\n\
         entity spec); a dotted edge means the referencing column is nullable.\n\n\
         ```mermaid\nerDiagram\n",
    );
    for entity in &entities {
        out.push_str(&format!("    {} {{\n", entity.relation));
        for col in &entity.columns {
            let mut markers: Vec<&str> = Vec::new();
            if entity.key.contains(&col.name) {
                markers.push("PK");
            }
            if col.references.is_some() {
                markers.push("FK");
            }
            if has_unique_single_index(entity, &col.name) {
                markers.push("UK");
            }
            let domain = col.accepted_values.as_ref().map(|values| {
                domain_comment(&values.iter().cloned().collect::<BTreeSet<String>>())
            });
            attribute_line(
                out,
                col.col_type.ducklake_type(),
                &col.name,
                &markers,
                domain.as_deref(),
            );
        }
        out.push_str("    }\n");
    }
    for entity in &entities {
        for col in &entity.columns {
            if let Some(reference) = &col.references {
                let line = if col.nullable { "}o..||" } else { "}o--||" };
                out.push_str(&format!(
                    "    {} {line} {} : \"{} → {}\"\n",
                    entity.relation, reference.relation, col.name, reference.column
                ));
            }
        }
    }
    out.push_str("```\n\n| relation | description |\n| --- | --- |\n");
    for entity in &entities {
        out.push_str(&format!(
            "| `{}` | {} |\n",
            entity.relation, entity.description
        ));
    }
}

/// Whether a non-partial unique index covers exactly this one column.
fn has_unique_single_index(entity: &Entity, column: &str) -> bool {
    entity.indexes.iter().any(|idx| {
        idx.unique && idx.r#where.is_none() && idx.columns.len() == 1 && idx.columns[0] == column
    })
}

// --------------------------------------------------------------------------- //
// the frontend's `erweb` schema — the drizzle snapshot
// --------------------------------------------------------------------------- //

/// The drizzle-kit snapshot (format 7), reduced to what the diagram needs. Unknown
/// fields are tolerated: drizzle owns this format, we only read it.
#[derive(Deserialize)]
struct DrizzleSnapshot {
    tables: BTreeMap<String, DrizzleTable>,
    #[serde(default)]
    enums: BTreeMap<String, DrizzleEnum>,
}

#[derive(Deserialize)]
struct DrizzleTable {
    name: String,
    columns: BTreeMap<String, DrizzleColumn>,
    #[serde(default)]
    indexes: BTreeMap<String, DrizzleIndex>,
    #[serde(default, rename = "foreignKeys")]
    foreign_keys: BTreeMap<String, DrizzleForeignKey>,
    #[serde(default, rename = "compositePrimaryKeys")]
    composite_primary_keys: BTreeMap<String, DrizzleCompositeKey>,
}

#[derive(Deserialize)]
struct DrizzleColumn {
    name: String,
    #[serde(rename = "type")]
    col_type: String,
    #[serde(default, rename = "primaryKey")]
    primary_key: bool,
    #[serde(default, rename = "notNull")]
    not_null: bool,
}

#[derive(Deserialize)]
struct DrizzleIndex {
    columns: Vec<DrizzleIndexColumn>,
    #[serde(default, rename = "isUnique")]
    is_unique: bool,
}

#[derive(Deserialize)]
struct DrizzleIndexColumn {
    expression: String,
    #[serde(default, rename = "isExpression")]
    is_expression: bool,
}

#[derive(Deserialize)]
struct DrizzleForeignKey {
    #[serde(rename = "tableFrom")]
    table_from: String,
    #[serde(rename = "tableTo")]
    table_to: String,
    #[serde(rename = "columnsFrom")]
    columns_from: Vec<String>,
    #[serde(rename = "columnsTo")]
    columns_to: Vec<String>,
    #[serde(default, rename = "onDelete")]
    on_delete: Option<String>,
}

#[derive(Deserialize)]
struct DrizzleCompositeKey {
    columns: Vec<String>,
}

#[derive(Deserialize)]
struct DrizzleEnum {
    name: String,
    values: Vec<String>,
}

fn erweb_section(snapshot: &str, out: &mut String) -> Result<(), ErdError> {
    let snapshot: DrizzleSnapshot = serde_json::from_str(snapshot)?;
    if snapshot.tables.is_empty() {
        return Ok(());
    }
    let enum_domains: BTreeMap<&str, &DrizzleEnum> = snapshot
        .enums
        .values()
        .map(|e| (e.name.as_str(), e))
        .collect();
    out.push_str(
        "\n## Frontend BFF — Postgres `erweb`\n\n\
         The frontend's own schema (drizzle ORM: auth, memberships, saved segments, its\n\
         audit trail), rendered from the latest drizzle snapshot. Its `org` columns name\n\
         `public.orgs` rows by convention but are deliberately not foreign keys — erserver\n\
         owns `public`, and the dependency arrow points one way.\n\n\
         ```mermaid\nerDiagram\n",
    );
    for table in snapshot.tables.values() {
        // Columns of the composite primary key, if the table has one.
        let composite: BTreeSet<&str> = table
            .composite_primary_keys
            .values()
            .flat_map(|k| k.columns.iter().map(String::as_str))
            .collect();
        let fk_columns: BTreeSet<&str> = table
            .foreign_keys
            .values()
            .flat_map(|fk| fk.columns_from.iter().map(String::as_str))
            .collect();
        out.push_str(&format!("    {} {{\n", table.name));
        for col in table.columns.values() {
            let mut markers: Vec<&str> = Vec::new();
            if col.primary_key || composite.contains(col.name.as_str()) {
                markers.push("PK");
            }
            if fk_columns.contains(col.name.as_str()) {
                markers.push("FK");
            }
            if has_unique_drizzle_index(table, &col.name) {
                markers.push("UK");
            }
            let domain = enum_domains
                .get(col.col_type.as_str())
                .map(|e| domain_comment(&e.values.iter().cloned().collect::<BTreeSet<String>>()));
            attribute_line(out, &col.col_type, &col.name, &markers, domain.as_deref());
        }
        out.push_str("    }\n");
    }
    for table in snapshot.tables.values() {
        for fk in table.foreign_keys.values() {
            let required = fk.columns_from.iter().all(|c| {
                table
                    .columns
                    .values()
                    .any(|col| col.name == *c && col.not_null)
            });
            let line = if required { "}o--||" } else { "}o..||" };
            let cascade = match fk.on_delete.as_deref() {
                Some("cascade") => ", on delete cascade",
                _ => "",
            };
            out.push_str(&format!(
                "    {} {line} {} : \"{} → {}{cascade}\"\n",
                fk.table_from,
                fk.table_to,
                fk.columns_from.join(", "),
                fk.columns_to.join(", "),
            ));
        }
    }
    out.push_str("```\n");
    Ok(())
}

/// Whether a non-expression unique drizzle index covers exactly this one column.
fn has_unique_drizzle_index(table: &DrizzleTable, column: &str) -> bool {
    table.indexes.values().any(|idx| {
        idx.is_unique
            && idx.columns.len() == 1
            && !idx.columns[0].is_expression
            && idx.columns[0].expression == column
    })
}

// --------------------------------------------------------------------------- //
// the data plane — the er-schema S5 registry
// --------------------------------------------------------------------------- //

fn lake_section(catalog: &Catalog, out: &mut String) {
    let specs = all_specs();
    out.push_str(
        "\n## Data plane — DuckLake `lake.main`\n\n\
         Every S5 relation: the engine's DDL-owned tables and the stage-materialised\n\
         marts (`CREATE TABLE AS SELECT` each run). The lake enforces `NOT NULL` and\n\
         nothing else — no foreign key exists — so every edge is dotted and name-implied:\n\
         the relation's columns contain the target's declared logical key. An implied\n\
         edge with several plausible targets is omitted rather than guessed.\n\n\
         ```mermaid\nerDiagram\n",
    );
    for spec in &specs {
        let pk: BTreeSet<&str> = primary_key(spec).iter().map(String::as_str).collect();
        out.push_str(&format!("    {} {{\n", spec.name));
        for col in &spec.columns {
            let markers: Vec<&str> = if pk.contains(col.name.as_str()) {
                vec!["PK"]
            } else {
                Vec::new()
            };
            let domain = spec.enums.get(&col.name).map(domain_comment);
            attribute_line(out, &col.r#type, &col.name, &markers, domain.as_deref());
        }
        out.push_str("    }\n");
    }
    for (child, parent, key_columns) in implied_edges(&specs) {
        out.push_str(&format!(
            "    {child} }}o..|| {parent} : \"{}\"\n",
            key_columns.join(", ")
        ));
    }
    out.push_str("```\n\n| relation | owner | description |\n| --- | --- | --- |\n");
    for spec in &specs {
        // The entity catalog carries prose for the relations it owns; the rest are
        // documented in `er-schema/src/model.rs`.
        let description = catalog
            .by_qualified_name(Store::Duckdb, &spec.name)
            .map_or("—", |e| e.description.as_str());
        out.push_str(&format!(
            "| `{}` | {} | {description} |\n",
            spec.name,
            spec.owner.as_str()
        ));
    }
}

/// The relation's primary key for display: its first unconditional logical key.
fn primary_key(spec: &TableSpec) -> &[String] {
    spec.keys
        .iter()
        .find(|k| k.r#where.is_none() && !k.columns.is_empty())
        .map_or(&[], |k| k.columns.as_slice())
}

/// The name-implied lake edges: `child` contains every column of `parent`'s
/// logical key. A key matched by several relations resolves to the DDL-owned one,
/// then to the one sharing the child's `acct_` namespace, else nobody. A mutual
/// match (two relations carrying each other's key) across owners is drawn once,
/// derived → source; within one owner it is two parallel same-grain relations
/// (`int_std_records` / `acct_int_std_records`), not a reference, and is dropped.
fn implied_edges(specs: &[TableSpec]) -> Vec<(String, String, Vec<String>)> {
    let owner_of: BTreeMap<&str, Owner> =
        specs.iter().map(|s| (s.name.as_str(), s.owner)).collect();

    let mut edges: Vec<(String, String, Vec<String>)> = Vec::new();
    for child in specs {
        let child_columns: BTreeSet<&str> = child.columns.iter().map(|c| c.name.as_str()).collect();
        // Group candidate targets by the key (column set) the child carries.
        let mut by_key: BTreeMap<Vec<String>, Vec<&TableSpec>> = BTreeMap::new();
        for target in specs {
            if target.name == child.name {
                continue;
            }
            // EVERY unconditional key can imply an edge — once primary keys are
            // the universal `id`, the natural key (published as a second
            // LogicalKey) is what a child actually carries. The bare `["id"]`
            // key itself is skipped: every relation has one, so "the child has
            // a column named id" names nothing.
            for key in &target.keys {
                if key.r#where.is_some()
                    || key.columns.is_empty()
                    || key.columns == ["id"]
                    || !key
                        .columns
                        .iter()
                        .all(|c| child_columns.contains(c.as_str()))
                {
                    continue;
                }
                let targets = by_key.entry(key.columns.clone()).or_default();
                if !targets.iter().any(|t: &&TableSpec| t.name == target.name) {
                    targets.push(target);
                }
            }
        }
        for (key_columns, mut targets) in by_key {
            if targets.iter().any(|t| t.owner == Owner::Ddl) {
                targets.retain(|t| t.owner == Owner::Ddl);
            }
            if targets.len() > 1 {
                let child_is_acct = child.name.starts_with("acct_");
                let same_namespace: Vec<&TableSpec> = targets
                    .iter()
                    .copied()
                    .filter(|t| t.name.starts_with("acct_") == child_is_acct)
                    .collect();
                if same_namespace.len() == 1 {
                    targets = same_namespace;
                }
            }
            let [target] = targets.as_slice() else {
                continue; // ambiguous: drawn by no rule
            };
            edges.push((child.name.clone(), target.name.clone(), key_columns));
        }
    }

    // A mutual match across owners is one derived → source edge (stage child, ddl
    // parent); within one owner the pair is two parallel same-grain relations,
    // not a reference, and both directions are dropped.
    let pairs: BTreeSet<(String, String)> = edges
        .iter()
        .map(|(c, p, _)| (c.clone(), p.clone()))
        .collect();
    edges.retain(|(child, parent, _)| {
        if !pairs.contains(&(parent.clone(), child.clone())) {
            return true;
        }
        owner_of[child.as_str()] == Owner::Stage && owner_of[parent.as_str()] == Owner::Ddl
    });
    edges
}

#[cfg(test)]
mod tests {
    use super::*;

    fn real_catalog() -> Catalog {
        let dir = concat!(env!("CARGO_MANIFEST_DIR"), "/../../../entities");
        Catalog::load_dir(dir).expect("entities load")
    }

    #[test]
    fn control_plane_draws_declared_foreign_keys() {
        let erd = emit_erd(&real_catalog(), None).expect("renders");
        assert!(erd.starts_with("<!-- @generated by er-entity-gen"));
        assert!(erd.contains("## Control plane — Postgres `public`"));
        // jobs.org is NOT NULL, so the edge is solid; the label names both columns.
        assert!(
            erd.contains("    jobs }o--|| orgs : \"org_id → id\""),
            "{erd}"
        );
        // Key and reference markers land on the attributes.
        assert!(erd.contains("varchar id PK"), "{erd}");
        assert!(erd.contains("varchar org_id FK"), "{erd}");
    }

    #[test]
    fn lake_covers_the_whole_registry_with_implied_edges() {
        let erd = emit_erd(&real_catalog(), None).expect("renders");
        // Every S5 relation appears as a table block.
        for spec in all_specs() {
            assert!(
                erd.contains(&format!("    {} {{\n", spec.name)),
                "missing {}",
                spec.name
            );
        }
        // Implied edges are dotted and resolve entity_id to the DDL-owned
        // `entities`, never a golden mart.
        assert!(erd.contains("    entity_membership }o..|| entities : \"entity_id\""));
        assert!(erd.contains("    golden_records }o..|| entities : \"entity_id\""));
        assert!(erd.contains("    run_stages }o..|| runs : \"run_id\""));
        // The standardized records reference their raw source rows.
        assert!(
            erd.contains("    int_std_records }o..|| raw_records"),
            "{erd}"
        );
        // A mutual match across owners (lineage and overrides share the
        // (entity_id, attribute) grain) is drawn once, derived → source.
        assert!(
            erd.contains("    golden_lineage }o..|| golden_overrides"),
            "{erd}"
        );
        assert!(
            !erd.contains("    golden_overrides }o..|| golden_lineage"),
            "{erd}"
        );
        // The person/account std relations are parallel twins, not references.
        assert!(
            !erd.contains("acct_int_std_records }o..|| int_std_records"),
            "{erd}"
        );
        assert!(
            !erd.contains("int_std_records }o..|| acct_int_std_records"),
            "{erd}"
        );
    }

    #[test]
    fn erweb_section_renders_drizzle_tables_and_foreign_keys() {
        let snapshot = r#"{
            "tables": {
                "erweb.users": {
                    "name": "users", "schema": "erweb",
                    "columns": {
                        "id": {"name": "id", "type": "text", "primaryKey": true, "notNull": true}
                    },
                    "indexes": {}, "foreignKeys": {}, "compositePrimaryKeys": {}
                },
                "erweb.sessions": {
                    "name": "sessions", "schema": "erweb",
                    "columns": {
                        "id": {"name": "id", "type": "text", "primaryKey": true, "notNull": true},
                        "user_id": {"name": "user_id", "type": "text", "primaryKey": false, "notNull": true},
                        "role": {"name": "role", "type": "org_role", "primaryKey": false, "notNull": true}
                    },
                    "indexes": {},
                    "foreignKeys": {
                        "sessions_user_id_users_id_fk": {
                            "tableFrom": "sessions", "tableTo": "users", "schemaTo": "erweb",
                            "columnsFrom": ["user_id"], "columnsTo": ["id"],
                            "onDelete": "cascade", "onUpdate": "no action"
                        }
                    },
                    "compositePrimaryKeys": {}
                }
            },
            "enums": {
                "erweb.org_role": {"name": "org_role", "schema": "erweb", "values": ["viewer", "steward", "admin"]}
            }
        }"#;
        let erd = emit_erd(&real_catalog(), Some(snapshot)).expect("renders");
        assert!(erd.contains("## Frontend BFF — Postgres `erweb`"));
        assert!(erd.contains("text user_id FK"), "{erd}");
        assert!(
            erd.contains("    sessions }o--|| users : \"user_id → id, on delete cascade\""),
            "{erd}"
        );
        assert!(
            erd.contains("org_role role \"in {admin, steward, viewer}\""),
            "{erd}"
        );
    }

    #[test]
    fn a_bad_snapshot_is_a_named_error_not_a_guess() {
        let err = emit_erd(&real_catalog(), Some("not json")).expect_err("must fail");
        assert!(matches!(err, ErdError::Snapshot(_)));
    }
}
