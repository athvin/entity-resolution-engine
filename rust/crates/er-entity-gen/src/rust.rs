//! The Rust emitter: one module per entity into the `er-entities` crate — the
//! struct (with `Option` for nullable columns), a `KEY`/`VERSION`/`RELATION`
//! constant, `columns()`, and `arrow_schema()` built from the one type map. It
//! emits source text; it links neither `arrow` nor `serde`.

use er_entity_spec::{ColumnType, Entity, Store, Wire};

use crate::casing::to_pascal_case;

/// Flatten a description to a single doc-comment line.
fn doc_line(prefix: &str, text: &str) -> String {
    let one_line = text.replace(['\n', '\r'], " ");
    format!("{prefix}/// {}\n", one_line.trim())
}

/// The Rust field type for a column, wrapping nullable columns in `Option`.
fn rust_field_type(col_type: ColumnType, nullable: bool) -> String {
    let base = col_type.rust_type();
    if nullable {
        format!("Option<{base}>")
    } else {
        base.to_string()
    }
}

/// The `arrow::datatypes::DataType` constructor expression for a column, on the
/// lake (naive-UTC timestamps, JSON as Utf8).
fn arrow_data_type(col_type: ColumnType) -> String {
    match col_type {
        ColumnType::Varchar | ColumnType::Json => "DataType::Utf8".to_string(),
        ColumnType::Bigint => "DataType::Int64".to_string(),
        ColumnType::Double => "DataType::Float64".to_string(),
        ColumnType::Boolean => "DataType::Boolean".to_string(),
        ColumnType::Date => "DataType::Date32".to_string(),
        ColumnType::Timestamp => "DataType::Timestamp(TimeUnit::Microsecond, None)".to_string(),
        ColumnType::ListVarchar => {
            "DataType::List(::std::sync::Arc::new(Field::new(\"item\", DataType::Utf8, true)))"
                .to_string()
        }
    }
}

/// Emit the full Rust module for one entity.
#[must_use]
pub fn emit_module(entity: &Entity) -> String {
    let struct_name = to_pascal_case(&entity.name);
    let mut out = String::new();

    out.push_str(&format!(
        "// @generated by er-entity-gen — DO NOT EDIT.\n// Source: entities/{}/entity.yaml\n\n",
        entity.name
    ));
    out.push_str("use serde::{Deserialize, Serialize};\n\n");

    // The struct.
    out.push_str(&doc_line("", &entity.description));
    out.push_str(
        "#[derive(Debug, Clone, PartialEq, Serialize, Deserialize, ::utoipa::ToSchema)]\n",
    );
    out.push_str(&format!("pub struct {struct_name} {{\n"));
    for column in &entity.columns {
        out.push_str(&doc_line("    ", &column.description));
        out.push_str(&format!(
            "    pub {}: {},\n",
            column.name,
            rust_field_type(column.col_type, column.nullable)
        ));
    }
    out.push_str("}\n\n");

    // The impl: constants + columns() + arrow_schema().
    out.push_str(&format!("impl {struct_name} {{\n"));
    let key_list = entity
        .key
        .iter()
        .map(|k| format!("\"{k}\""))
        .collect::<Vec<_>>()
        .join(", ");
    out.push_str("    /// The logical key columns.\n");
    out.push_str(&format!(
        "    pub const KEY: &'static [&'static str] = &[{key_list}];\n"
    ));
    out.push_str("    /// The entity schema version; bumped only on a breaking change.\n");
    out.push_str(&format!(
        "    pub const VERSION: u64 = {};\n",
        entity.version
    ));
    out.push_str("    /// The relation (table) name.\n");
    out.push_str(&format!(
        "    pub const RELATION: &'static str = \"{}\";\n",
        entity.relation
    ));
    let store_qualifier = if entity.has_store(Store::Duckdb) {
        Store::Duckdb.qualifier()
    } else {
        Store::Postgres.qualifier()
    };
    out.push_str("    /// The store-qualified schema this entity lives in.\n");
    out.push_str(&format!(
        "    pub const STORE: &'static str = \"{store_qualifier}\";\n\n"
    ));

    // columns()
    let col_list = entity
        .columns
        .iter()
        .map(|c| format!("\"{}\"", c.name))
        .collect::<Vec<_>>()
        .join(", ");
    out.push_str("    /// The declaration-ordered column names.\n");
    out.push_str("    #[must_use]\n");
    out.push_str("    pub fn columns() -> &'static [&'static str] {\n");
    out.push_str(&format!("        &[{col_list}]\n"));
    out.push_str("    }\n\n");

    // arrow_schema() — only when the entity crosses the Arrow wire. Control-plane
    // entities (JSON wire only) have no Arrow schema.
    if entity.has_wire(Wire::Arrow) {
        emit_arrow_schema(&mut out, entity, store_qualifier);
    }
    out.push_str("}\n");

    // The bulk-append primitive — only for lake entities that ask for it.
    if entity.generate.append && entity.has_store(Store::Duckdb) {
        emit_append_rows(&mut out, entity);
    }

    out
}

/// The append transport type for a column: timestamps, dates and JSON cross as
/// text (the lake-write convention — the cast lives in the generated SQL).
fn append_field_type(col_type: ColumnType, nullable: bool) -> String {
    let base = match col_type {
        ColumnType::Varchar | ColumnType::Timestamp | ColumnType::Date | ColumnType::Json => {
            "String"
        }
        ColumnType::Bigint => "i64",
        ColumnType::Double => "f64",
        ColumnType::Boolean => "bool",
        ColumnType::ListVarchar => {
            panic!("an append entity cannot carry a list column (duckdb-rs has no LIST binding)")
        }
    };
    if nullable {
        format!("Option<{base}>")
    } else {
        base.to_string()
    }
}

/// The cast a bound append value needs to land in its column type.
fn append_cast(col_type: ColumnType) -> &'static str {
    match col_type {
        ColumnType::Json => "::json",
        ColumnType::Timestamp => "::timestamp",
        ColumnType::Date => "::date",
        _ => "",
    }
}

/// Emit the `AppendRow` transport struct + `append_rows`: variable-arity row
/// batches as chunked, bound-parameter `INSERT .. VALUES`, the tuple shape and
/// casts generated from the entity's columns.
fn emit_append_rows(out: &mut String, entity: &Entity) {
    let cols = entity.columns.len();
    out.push_str("\n/// The bulk-append transport row: timestamps/dates/JSON cross as text\n");
    out.push_str("/// with explicit casts in the generated SQL (the lake-write convention).\n");
    out.push_str("#[derive(Debug, Clone, PartialEq)]\n");
    out.push_str("pub struct AppendRow {\n");
    for column in &entity.columns {
        out.push_str(&doc_line("    ", &column.description));
        out.push_str(&format!(
            "    pub {}: {},\n",
            column.name,
            append_field_type(column.col_type, column.nullable)
        ));
    }
    out.push_str("}\n\n");

    let tuple_template = entity
        .columns
        .iter()
        .enumerate()
        .map(|(i, c)| format!("${{p{i}}}{}", append_cast(c.col_type)))
        .collect::<Vec<_>>()
        .join(", ");
    let placeholder_args = (0..cols)
        .map(|i| format!("p{i} = base + {}", i + 1))
        .collect::<Vec<_>>()
        .join(", ");

    out.push_str(&format!(
        "/// Append rows to `lake.main.{}` in bound-parameter chunks (the shape and\n",
        entity.relation
    ));
    out.push_str("/// casts are generated from the entity). Returns the appended row count.\n");
    out.push_str("///\n/// # Errors\n/// Propagates the DuckDB prepare/execute error.\n");
    out.push_str("pub fn append_rows(\n");
    out.push_str("    conn: &::duckdb::Connection,\n");
    out.push_str("    rows: &[AppendRow],\n");
    out.push_str(") -> ::duckdb::Result<usize> {\n");
    out.push_str(&format!("    const COLS: usize = {cols};\n"));
    out.push_str("    const CHUNK: usize = 500;\n");
    out.push_str("    for chunk in rows.chunks(CHUNK) {\n");
    out.push_str("        let mut tuples = Vec::with_capacity(chunk.len());\n");
    out.push_str("        for i in 0..chunk.len() {\n");
    out.push_str("            let base = i * COLS;\n");
    out.push_str(&format!(
        "            tuples.push(format!(\n                \"({tuple_template})\",\n                {placeholder_args}\n            ));\n"
    ));
    out.push_str("        }\n");
    out.push_str(&format!(
        "        let sql = format!(\n            \"INSERT INTO lake.main.{} VALUES {{}}\",\n            tuples.join(\", \")\n        );\n",
        entity.relation
    ));
    out.push_str(
        "        let mut params: Vec<&dyn ::duckdb::ToSql> = Vec::with_capacity(chunk.len() * COLS);\n",
    );
    out.push_str("        for row in chunk {\n");
    for column in &entity.columns {
        out.push_str(&format!("            params.push(&row.{});\n", column.name));
    }
    out.push_str("        }\n");
    out.push_str("        conn.execute(&sql, params.as_slice())?;\n");
    out.push_str("    }\n");
    out.push_str("    Ok(rows.len())\n");
    out.push_str("}\n");
}

/// Emit the `arrow_schema()` function body for an Arrow-wire entity.
fn emit_arrow_schema(out: &mut String, entity: &Entity, store_qualifier: &str) {
    out.push_str("\n    /// The Arrow schema this entity streams as, with key, store and\n");
    out.push_str("    /// version carried in the schema metadata.\n");
    out.push_str("    #[must_use]\n");
    out.push_str("    pub fn arrow_schema() -> ::arrow::datatypes::Schema {\n");
    out.push_str("        use ::arrow::datatypes::{DataType, Field, Schema, TimeUnit};\n");
    out.push_str("        let fields: Vec<Field> = vec![\n");
    for column in &entity.columns {
        let data_type = arrow_data_type(column.col_type);
        if column.col_type == ColumnType::Json {
            out.push_str(&format!(
                "            Field::new(\"{}\", {}, {}).with_metadata(::std::collections::HashMap::from([(\"er.json\".to_string(), \"true\".to_string())])),\n",
                column.name, data_type, column.nullable
            ));
        } else {
            out.push_str(&format!(
                "            Field::new(\"{}\", {}, {}),\n",
                column.name, data_type, column.nullable
            ));
        }
    }
    out.push_str("        ];\n");
    out.push_str("        let metadata = ::std::collections::HashMap::from([\n");
    out.push_str(&format!(
        "            (\"er.key\".to_string(), \"{}\".to_string()),\n",
        entity.key.join(",")
    ));
    out.push_str(&format!(
        "            (\"er.store\".to_string(), \"{store_qualifier}\".to_string()),\n"
    ));
    out.push_str(&format!(
        "            (\"er.relation\".to_string(), \"{}\".to_string()),\n",
        entity.relation
    ));
    out.push_str(&format!(
        "            (\"er.schema_version\".to_string(), \"{}\".to_string()),\n",
        entity.version
    ));
    out.push_str("        ]);\n");
    out.push_str("        Schema::new(fields).with_metadata(metadata)\n");
    out.push_str("    }\n");
}
