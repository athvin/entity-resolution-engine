//! The TypeScript emitters: the binding (`bindings/<Entity>.ts`, the type) and the
//! reader (`readers/<Entity>.ts`, an Arrow `Table` -> `Entity[]` function). Both
//! come from the one type map, so the Arrow lane and the JSON lane yield the
//! identical shape. The binding is emitted directly from the vocabulary rather
//! than through ts-rs, which gives `i64 -> number` without an env-var override and
//! keeps every emitter in this one crate.

use er_entity_spec::{ColumnType, Entity};

use crate::casing::to_pascal_case;

/// A JSDoc line from a description.
fn jsdoc(indent: &str, text: &str) -> String {
    let one_line = text.replace(['\n', '\r'], " ");
    format!("{indent}/** {} */\n", one_line.trim())
}

/// The TypeScript field type for a column, with `| null` for nullable. `unknown`
/// (the JSON type) already subsumes `null`, so a nullable JSON column stays
/// `unknown` rather than the redundant `unknown | null` the frontend linter flags.
fn ts_field_type(col_type: ColumnType, nullable: bool) -> String {
    let base = col_type.typescript_type();
    if nullable && col_type != ColumnType::Json {
        format!("{base} | null")
    } else {
        base.to_string()
    }
}

/// Emit `bindings/<Entity>.ts` — the type the browser and BFF use.
#[must_use]
pub fn emit_binding(entity: &Entity) -> String {
    let type_name = to_pascal_case(&entity.name);
    let mut out = String::new();
    out.push_str(&format!(
        "// @generated by er-entity-gen — DO NOT EDIT.\n// Source: entities/{}/entity.yaml\n\n",
        entity.name
    ));
    out.push_str(&jsdoc("", &entity.description));
    out.push_str(&format!("export interface {type_name} {{\n"));
    for column in &entity.columns {
        out.push_str(&jsdoc("  ", &column.description));
        out.push_str(&format!(
            "  {}: {};\n",
            column.name,
            ts_field_type(column.col_type, column.nullable)
        ));
    }
    out.push_str("}\n");
    out
}

/// The per-column conversion expression the reader uses, reading `col` (a vector)
/// at index `i`. Nullable columns short-circuit a null vector value.
fn ts_convert(col_type: ColumnType) -> &'static str {
    match col_type {
        // A varchar and a JSON column both cross as Utf8 text; JSON is left as text.
        ColumnType::Varchar | ColumnType::Json => "readUtf8(v)",
        ColumnType::Bigint => "readInt64(v)",
        ColumnType::Double => "readFloat(v)",
        ColumnType::Boolean => "readBool(v)",
        ColumnType::Date => "readDate32(v)",
        ColumnType::Timestamp => "readTimestamp(v)",
        ColumnType::ListVarchar => "readListUtf8(v)",
    }
}

/// Emit `readers/<Entity>.ts` — the Arrow `Table` -> `Entity[]` function with an
/// in-band schema and version check, then a per-column conversion by the type map.
#[must_use]
pub fn emit_reader(entity: &Entity) -> String {
    let type_name = to_pascal_case(&entity.name);
    let mut out = String::new();
    out.push_str(&format!(
        "// @generated by er-entity-gen — DO NOT EDIT.\n// Source: entities/{}/entity.yaml\n\n",
        entity.name
    ));
    out.push_str("import type { Table } from \"apache-arrow\";\n");
    out.push_str(&format!(
        "import type {{ {type_name} }} from \"../bindings/{type_name}\";\n\n"
    ));

    // The conversion helpers, emitted once per reader (self-contained).
    out.push_str(READER_HELPERS);
    out.push('\n');

    // The non-null column names the schema check requires, and the version.
    let required: Vec<&str> = entity
        .columns
        .iter()
        .filter(|c| !c.nullable)
        .map(|c| c.name.as_str())
        .collect();
    let required_list = required
        .iter()
        .map(|n| format!("\"{n}\""))
        .collect::<Vec<_>>()
        .join(", ");

    out.push_str(&format!(
        "const EXPECTED_VERSION = \"{}\";\nconst REQUIRED: readonly string[] = [{required_list}];\n\n",
        entity.version
    ));

    out.push_str(&format!(
        "/** Decode an Arrow table into {type_name}[] after checking the in-band schema. */\n"
    ));
    out.push_str(&format!(
        "export function read{type_name}(table: Table): {type_name}[] {{\n"
    ));
    out.push_str("  const meta = table.schema.metadata;\n");
    out.push_str("  const version = meta.get(\"er.schema_version\");\n");
    out.push_str("  if (version !== undefined && version !== EXPECTED_VERSION) {\n");
    out.push_str(&format!(
        "    throw new Error(`{type_name}: schema version ${{version}} != expected ${{EXPECTED_VERSION}}`);\n"
    ));
    out.push_str("  }\n");
    out.push_str("  for (const name of REQUIRED) {\n");
    out.push_str("    if (table.getChild(name) == null) {\n");
    out.push_str(&format!(
        "      throw new Error(`{type_name}: required column ${{name}} is missing from the stream`);\n"
    ));
    out.push_str("    }\n");
    out.push_str("  }\n");
    out.push_str(&format!("  const rows: {type_name}[] = [];\n"));
    out.push_str("  for (let i = 0; i < table.numRows; i++) {\n");
    out.push_str("    rows.push({\n");
    for column in &entity.columns {
        let convert = ts_convert(column.col_type);
        // A nullable column reads `null` when the vector is absent or the value is
        // null; a required column has been proven present above.
        out.push_str(&format!(
            "      {name}: ((v) => (v == null ? null : {convert}))(table.getChild(\"{name}\")?.get(i)),\n",
            name = column.name,
        ));
    }
    out.push_str(&format!("    }} as {type_name});\n"));
    out.push_str("  }\n");
    out.push_str("  return rows;\n");
    out.push_str("}\n");
    out
}

/// The conversion helpers baked into every reader. Deliberately defensive about the
/// several shapes apache-arrow returns across versions (bigint vs number, Date vs
/// day-count); the exact behaviour is pinned against the installed apache-arrow in
/// the frontend tier.
const READER_HELPERS: &str = r#"function readUtf8(v: unknown): string {
  return String(v);
}
function readInt64(v: unknown): number {
  const n = typeof v === "bigint" ? Number(v) : Number(v);
  if (!Number.isSafeInteger(n)) {
    throw new Error(`int64 value ${String(v)} is outside the safe-integer range`);
  }
  return n;
}
function readFloat(v: unknown): number {
  return Number(v);
}
function readBool(v: unknown): boolean {
  return Boolean(v);
}
function readDate32(v: unknown): string {
  // Date32 is days since the epoch; apache-arrow may hand back a Date or a number.
  const d = v instanceof Date ? v : new Date((v as number) * 86_400_000);
  return d.toISOString().slice(0, 10);
}
function readTimestamp(v: unknown): string {
  // Timestamp(us) — normalise bigint micros / number millis / Date to an ISO string.
  if (v instanceof Date) return v.toISOString();
  const ms = typeof v === "bigint" ? Number(v / 1000n) : Number(v);
  return new Date(ms).toISOString();
}
function readListUtf8(v: unknown): string[] {
  const arr = v as { toArray?: () => unknown[] } | unknown[];
  const items = Array.isArray(arr) ? arr : (arr.toArray?.() ?? []);
  return items.map((x) => String(x));
}
"#;
