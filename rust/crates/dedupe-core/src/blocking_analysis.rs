//! Blocking cardinality analysis: how many record comparisons each blocking
//! rule generates (after the "AND NOT preceding rules" dedup), cumulatively,
//! against the total possible comparisons (data only — no chart).
//!
//! Use this before `predict()` to check that blocking rules generate a
//! tractable number of pairs without being so tight they miss matches.

use std::collections::BTreeMap;

use crate::blocking::BlockingRule;
use crate::error::{DedupeError, Result};
use crate::session::{Session, TableHandle};
use crate::settings::Settings;
use crate::sql::columns;
use crate::sql::pipeline::CtePipeline;
use crate::stages::block::{self, BLOCKED_ID_PAIRS};
use crate::stages::uid_expr_for;
use crate::training::prior::total_possible_comparisons;

#[derive(Debug, Clone, PartialEq)]
pub struct BlockingRuleCount {
    pub blocking_rule: String,
    /// 0-based rule index (the `match_key`).
    pub match_key: i64,
    /// Pairs generated by this rule that were NOT already generated by an
    /// earlier rule.
    pub marginal_comparison_count: i64,
    /// Running total of marginal counts over the rules so far.
    pub cumulative_comparison_count: i64,
    /// Total possible comparisons (the cartesian count) for the link type.
    pub total_possible_comparison_count: i64,
}

/// Count comparisons generated by each blocking rule, cumulatively, exactly
/// (no sampling). `rules` are raw SQL blocking conditions over `l.`/`r.`.
pub fn count_comparisons_from_blocking_rules(
    session: &Session,
    settings: &Settings,
    concat: &TableHandle,
    rules: &[String],
) -> Result<Vec<BlockingRuleCount>> {
    let total = total_possible_comparisons(session, concat, settings)? as i64;
    let uid = uid_expr_for(settings);

    let brs: Vec<BlockingRule> = rules
        .iter()
        .enumerate()
        .map(|(i, sql)| BlockingRule {
            index: i,
            sql: sql.clone(),
            arrays_to_explode: Vec::new(),
        })
        .collect();

    // Materialize deduped blocked pairs and count per match_key.
    let mut p = CtePipeline::new().with_input(concat);
    p.enqueue(
        block::blocked_id_pairs_sql(
            &brs,
            &uid,
            settings.link_type,
            &settings.source_dataset_column,
            concat.templated.as_str(),
            &[],
            None,
        ),
        BLOCKED_ID_PAIRS,
    );
    let blocked = session.materialize(&p)?;
    let rows = session.query_strings(&format!(
        "select match_key, count(*) from {} group by match_key",
        blocked.physical
    ))?;
    session.drop_table(&blocked)?;

    let counts: BTreeMap<i64, i64> = rows
        .into_iter()
        .map(|r| (r[0].parse::<i64>().unwrap(), r[1].parse::<i64>().unwrap()))
        .collect();

    let mut out = Vec::with_capacity(rules.len());
    let mut cumulative = 0i64;
    for (i, sql) in rules.iter().enumerate() {
        let marginal = *counts.get(&(i as i64)).unwrap_or(&0);
        cumulative += marginal;
        out.push(BlockingRuleCount {
            blocking_rule: sql.clone(),
            match_key: i as i64,
            marginal_comparison_count: marginal,
            cumulative_comparison_count: cumulative,
            total_possible_comparison_count: total,
        });
    }
    Ok(out)
}

/// A block (distinct blocking-key value) and its equi-join cardinality.
#[derive(Debug, Clone, PartialEq)]
pub struct LargestBlock {
    pub key_values: Vec<String>,
    pub count_l: i64,
    pub count_r: i64,
    pub block_count: i64,
}

/// The `n` blocking-key values producing the largest equi-join blocks
/// (`count_l * count_r`). The rule must
/// be a pure equi-join (a conjunction of column equalities, e.g. `block_on`);
/// filter conditions are not supported. Dedupe path (both sides = concat).
pub fn n_largest_blocks(
    session: &Session,
    settings: &Settings,
    concat: &TableHandle,
    rule: &str,
    n_largest: usize,
) -> Result<Vec<LargestBlock>> {
    let _ = settings;
    let keys = columns::equi_join_columns(rule, "n_largest_blocks")?.ok_or_else(|| {
        DedupeError::settings(format!(
            "n_largest_blocks requires a pure equi-join blocking rule (got `{rule}`)"
        ))
    })?;
    let key_select = keys
        .iter()
        .enumerate()
        .map(|(i, k)| format!("\"{k}\" as key_{i}"))
        .collect::<Vec<_>>()
        .join(", ");
    let key_cols = (0..keys.len())
        .map(|i| format!("key_{i}"))
        .collect::<Vec<_>>()
        .join(", ");

    let sql = format!(
        "with l as (select {key_select}, count(*) as count_l from {c} group by {gb}),\n\
             r as (select {key_select}, count(*) as count_r from {c} group by {gb})\n\
         select {key_cols}, count_l, count_r, count_l * count_r as block_count\n\
         from l join r using ({key_cols})\n\
         order by block_count desc\n\
         limit {n_largest}",
        c = concat.physical,
        gb = keys
            .iter()
            .map(|k| format!("\"{k}\""))
            .collect::<Vec<_>>()
            .join(", "),
    );
    let rows = session.query_strings(&sql)?;
    let n_keys = keys.len();
    Ok(rows
        .into_iter()
        .map(|r| LargestBlock {
            key_values: r[..n_keys].to_vec(),
            count_l: r[n_keys].parse().unwrap(),
            count_r: r[n_keys + 1].parse().unwrap(),
            block_count: r[n_keys + 2].parse().unwrap(),
        })
        .collect())
}
