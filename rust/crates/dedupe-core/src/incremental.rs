//! Incremental linkage — `predict_between` and `predict_within`, scoped to
//! dedupe.
//!
//! The use case: a model has been trained on an existing dataset, and a new
//! batch of records arrives. Rather than re-running the whole pipeline over
//! the combined data, we:
//!
//! - [`predict_between`]: score candidate pairs *between* the existing records
//!   and the new batch (cross pairs only, never within either side), and
//! - [`predict_within`]: score candidate pairs *within* the new batch.
//!
//! Both score with the model's parameters and with term frequencies taken
//! from the established data (so a new record's term frequency reflects the
//! established corpus; a value unseen there gets no TF adjustment).

use crate::error::Result;
use crate::predict;
use crate::session::{Session, TableHandle};
use crate::settings::Settings;
use crate::sql::pipeline::CtePipeline;
use crate::stages::block::{self, BLOCKED_ID_PAIRS};
use crate::stages::score::{self, DF_MATCH_WEIGHT_PARTS, DF_PREDICT};
use crate::stages::tf;
use crate::stages::uid_expr_for;
use crate::stages::vectors::{self, BLOCKED_WITH_COLS, DF_COMPARISON_VECTORS};

const DF_CONCAT_WITH_TF_LEFT: &str = "__splink__df_concat_with_tf_left";
const DF_CONCAT_WITH_TF_RIGHT: &str = "__splink__df_concat_with_tf_right";

/// Score candidate pairs between an existing collection and a new batch.
///
/// `existing_concat` / `new_concat` are `__splink__df_concat`-shaped tables
/// (projections of each side's records); `tf_tables` are the term-frequency
/// tables computed from the existing data. Candidate pairs are generated by
/// an inner join of existing x new on each blocking rule (no within-side
/// pairs), scored with the model parameters in `settings`.
pub fn predict_between(
    session: &Session,
    settings: &Settings,
    existing_concat: &TableHandle,
    new_concat: &TableHandle,
    tf_tables: &[TableHandle],
    threshold_match_weight: Option<f64>,
) -> Result<TableHandle> {
    let uid = uid_expr_for(settings);

    // Cross-table blocked pairs (existing = left, new = right). Both concats
    // carry the `__splink__df_concat` templated name, so the SQL references
    // them by physical name to disambiguate the sides (no pipeline inputs).
    let mut bp = CtePipeline::new();
    bp.enqueue(
        block::blocked_id_pairs_cross_sql(
            &settings.blocking_rules,
            &uid,
            &existing_concat.physical,
            &new_concat.physical,
        ),
        BLOCKED_ID_PAIRS,
    );
    let blocked = session.materialize(&bp)?;

    let tf_columns = settings.tf_columns();
    let mut p = CtePipeline::new().with_input(&blocked);
    for t in tf_tables {
        p.add_input(t);
    }
    // concat_with_tf for each side (same TF tables, different source concat).
    // Referenced by physical name since both concats share a templated name.
    p.enqueue(
        tf::concat_with_tf_sql_from(&existing_concat.physical, &tf_columns, &settings.tf_prefix),
        DF_CONCAT_WITH_TF_LEFT,
    );
    p.enqueue(
        tf::concat_with_tf_sql_from(&new_concat.physical, &tf_columns, &settings.tf_prefix),
        DF_CONCAT_WITH_TF_RIGHT,
    );
    p.enqueue(
        vectors::blocked_with_cols_sql_tables(
            settings,
            &uid,
            BLOCKED_ID_PAIRS,
            DF_CONCAT_WITH_TF_LEFT,
            DF_CONCAT_WITH_TF_RIGHT,
        ),
        BLOCKED_WITH_COLS,
    );
    p.enqueue(
        vectors::comparison_vectors_sql(settings),
        DF_COMPARISON_VECTORS,
    );
    p.enqueue(
        score::match_weight_parts_sql(settings)?,
        DF_MATCH_WEIGHT_PARTS,
    );
    p.enqueue(
        score::predict_sql(settings, settings.prior, false, threshold_match_weight)?,
        DF_PREDICT,
    );
    let out = session.materialize(&p)?;
    session.drop_table(&blocked)?;
    Ok(out)
}

/// Score the full cartesian product of two record collections with no
/// blocking (`score_pairs`): every left record against every right
/// record, scored with the model and the established TF tables. Realtime /
/// ad-hoc pair scoring.
pub fn score_pairs(
    session: &Session,
    settings: &Settings,
    left_concat: &TableHandle,
    right_concat: &TableHandle,
    tf_tables: &[TableHandle],
    threshold_match_weight: Option<f64>,
) -> Result<TableHandle> {
    // A `1=1` cross block over left x right (no dedup, no source filter) is
    // exactly the cartesian score; reuse predict_between with that one rule.
    let mut s = settings.clone();
    s.blocking_rules = vec![crate::blocking::BlockingRule {
        index: 0,
        sql: "1=1".to_string(),
        arrays_to_explode: Vec::new(),
    }];
    predict_between(
        session,
        &s,
        left_concat,
        right_concat,
        tf_tables,
        threshold_match_weight,
    )
}

/// Score candidate pairs within a supplied collection (e.g. the new batch),
/// using term frequencies from the established data. This is the ordinary
/// predict pipeline over `concat` with externally supplied TF tables.
pub fn predict_within(
    session: &Session,
    settings: &Settings,
    concat: &TableHandle,
    tf_tables: &[TableHandle],
    threshold_match_weight: Option<f64>,
) -> Result<TableHandle> {
    let blocked = predict::materialize_blocked_pairs(session, settings, concat)?;
    let pipeline = predict::predict_pipeline(
        settings,
        concat,
        tf_tables,
        &blocked,
        threshold_match_weight,
    )?;
    let out = session.materialize(&pipeline)?;
    session.drop_table(&blocked)?;
    Ok(out)
}
