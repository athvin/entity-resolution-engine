SELECT
  id,
  org_id,
  job_id,
  task_id,
  seq,
  try_number,
  live,
  archived_reason,
  kind,
  state,
  trigger_rule,
  upstream,
  teardown,
  segment,
  resource_class,
  next_resource_class,
  escalated_from,
  max_tries,
  launches,
  max_launches,
  not_before,
  input,
  output,
  outcome,
  exit_code,
  termination_reason,
  error_class,
  error_detail,
  owner_epoch,
  k8s_job_name,
  pod_name,
  pod_uid,
  node_name,
  image_digest,
  snapshot_start,
  snapshot_end,
  counters,
  trace_context,
  token_hash,
  scheduled_at,
  queued_at,
  started_at,
  heartbeat_at,
  finished_at,
  created_at,
  updated_at
FROM public.task_instances
WHERE live IS TRUE AND kind = 'pod'
  AND state IN ('queued', 'running', 'restarting', 'canceling')
  AND k8s_job_name IS DISTINCT FROM 'inproc'
ORDER BY job_id, seq
