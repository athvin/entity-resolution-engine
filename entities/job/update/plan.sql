UPDATE public.jobs
SET state = 'running', run_id = id, structural_fingerprint = $structural_fingerprint,
    policy_hash = $policy_hash, image_digest = $image_digest, owner_epoch = $owner_epoch,
    updated_at = now()
WHERE id = $job_id AND state = 'dispatching'
RETURNING
  id,
  org_id,
  kind,
  params,
  state,
  priority,
  idempotency_key,
  run_id,
  attempt,
  max_attempts,
  error_class,
  error_detail,
  not_before,
  created_by,
  schedule_id,
  resource_class,
  trace_context,
  structural_fingerprint,
  policy_hash,
  image_digest,
  clear_number,
  owner_epoch,
  created_at,
  updated_at,
  started_at,
  finished_at
