UPDATE public.jobs
SET state = CASE WHEN state = 'queued' THEN 'canceled' ELSE 'canceling' END,
    finished_at = CASE WHEN state = 'queued' THEN now() ELSE finished_at END,
    updated_at = now()
WHERE id = $job_id AND org_id = $org_id AND state IN ('queued', 'dispatching', 'running')
RETURNING
  id,
  org_id,
  kind,
  params,
  state,
  priority,
  idempotency_key,
  run_id,
  attempt,
  max_attempts,
  error_class,
  error_detail,
  not_before,
  created_by,
  schedule_id,
  resource_class,
  trace_context,
  structural_fingerprint,
  policy_hash,
  image_digest,
  clear_number,
  owner_epoch,
  created_at,
  updated_at,
  started_at,
  finished_at
