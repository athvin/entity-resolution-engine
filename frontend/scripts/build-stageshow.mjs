// Rebuild the minimal runtime from the repo-owned MIT Stageshow source.
import { createRequire } from "node:module";
import { mkdir, writeFile, copyFile, mkdtemp, rm } from "node:fs/promises";
import { tmpdir } from "node:os";
import { resolve, join } from "node:path";
import { execFileSync } from "node:child_process";
import { fileURLToPath } from "node:url";
import { format } from "prettier";

const root = fileURLToPath(new URL("../", import.meta.url));
const kit = resolve(root, "../.claude/skills/stageshow/kit");
const out = resolve(root, "src/components/marketing/demo/vendor");
const require = createRequire(import.meta.url);
const esbuild = require("esbuild");
const scratch = await mkdtemp(join(tmpdir(), "dupezero-stageshow-"));
const exports = `export { Stage } from "${kit}/stage";
export { Window, Bar, Text } from "${kit}/window";
export { Row } from "${kit}/parts/Row";
export { Badge } from "${kit}/controls/Badge";
export type { Act } from "${kit}/act";
`;
try {
  await mkdir(out, { recursive: true });
  const result = await esbuild.build({
    stdin: { contents: exports, resolveDir: root, loader: "ts" },
    absWorkingDir: resolve(root, ".."),
    bundle: true,
    format: "esm",
    platform: "browser",
    jsx: "automatic",
    external: ["react", "react-dom", "react/jsx-runtime"],
    outfile: join(out, "index.js"),
    write: false,
    banner: { js: "// Generated by scripts/build-stageshow.mjs. MIT; see LICENSE." },
  });
  for (const file of result.outputFiles) {
    await writeFile(
      file.path,
      await format(file.text.replace(/\/\/ eslint-disable[^\n]*/g, ""), {
        parser: file.path.endsWith(".css") ? "css" : "babel",
      }),
    );
  }
  const config = join(scratch, "tsconfig.json");
  await writeFile(
    config,
    JSON.stringify({
      compilerOptions: {
        target: "ES2022",
        module: "ESNext",
        moduleResolution: "bundler",
        jsx: "react-jsx",
        declaration: true,
        emitDeclarationOnly: true,
        noCheck: true,
        outDir: join(out, "types"),
        rootDir: kit,
      },
      files: ["stage.tsx", "window.tsx", "parts/Row.tsx", "controls/Badge.tsx"].map((f) =>
        join(kit, f),
      ),
    }),
  );
  execFileSync(resolve(root, "node_modules/.bin/tsc"), ["-p", config], { stdio: "inherit" });
  await writeFile(join(out, "index.d.ts"), exports.replaceAll(kit + "/", "./types/"));
  await copyFile(resolve(kit, "../LICENSE"), join(out, "LICENSE"));
  await writeFile(
    join(out, "README.md"),
    `# Stageshow runtime\n\nGenerated from the repository's MIT-licensed Stageshow kit. Only Stage, Window, Row, Badge and their dependencies ship. Source and notices live under .claude/skills/stageshow. Rebuild from frontend with node scripts/build-stageshow.mjs. Do not edit generated files. Product scenes and styling live beside this directory.\n`,
  );
} finally {
  await rm(scratch, { recursive: true, force: true });
}
