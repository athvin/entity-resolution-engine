/**
 * The wire-contract gate: a response shape the UI declares may not invent
 * fields the backend does not have.
 *
 * `rust/crates/er-server/tests/mock_contract.rs` compares route and method, and
 * that is all it compares. The defect class it cannot see has now recurred
 * seven times in this program, every time as *the frontend states a contract
 * the backend never fulfilled*, and every time green in all three mock-backed
 * tiers — because the mock encodes the frontend's belief about the API rather
 * than the server's behaviour. The sharpest case: `JobRow` declared
 * `progress: { stages?: … }` **required**, three components read
 * `job.progress.stages` unguarded, the mock fabricated the object at 11 sites,
 * and er-server sends no such field and has no producer for one. The run detail
 * page, the runs list and the dashboard's active-job line all threw against
 * every real backend while CI was green.
 *
 * The authority here is `src/lib/entities/bindings/*` — generated by
 * `er-entity-gen` from `entities/*​/entity.yaml` and drift-gated by
 * `er-entity verify`, so it cannot disagree with what the server serializes.
 * The check is **compile-time**: `NoUndeclaredFields` resolves to `true` when a
 * UI shape's keys are a subset of its entity's, and to an error object naming
 * the offending keys otherwise, so `tsc --noEmit` fails in the already-required
 * `lint + types + unit` context. The runtime assertions below only keep the
 * table honest about itself.
 *
 * ## Adding a pair
 *
 * A response interface that mirrors an entity row belongs in `PAIRS` below.
 * Fields the **BFF composes** (joined from the erweb registry, the credential
 * vault, or computed) are legitimate and go in the third type argument with a
 * comment saying where each comes from — the point of the gate is that such a
 * field is *declared* rather than assumed.
 *
 * ## What this does NOT cover, and why
 *
 * Envelope and ordering mismatches. W0.5b's bug was `forward<unknown[]>` over
 * `{jobs: […]}` — a per-path response *shape*, not a field name. W0.5d's was a
 * mock serving receipts newest-first for an endpoint that pages oldest-first.
 * Arbitrating either needs the OpenAPI document to describe paths, and
 * `src/lib/api/openapi.json` documents **zero** of them: `er-server/src/openapi.rs`
 * registers `components.schemas` only, deliberately ("per-path operation docs
 * ride on top later"). Those 12 schemas are these same entity structs, which is
 * why the field half is buildable today and the envelope half is not. Closing
 * it means `#[utoipa::path]` on the handlers first.
 */
import { describe, expect, it } from "vitest";

import type { ConfigVersion } from "@/lib/entities/bindings/ConfigVersion";
import type { GoldenLineage } from "@/lib/entities/bindings/GoldenLineage";
import type { IngestBatch } from "@/lib/entities/bindings/IngestBatch";
import type { Job } from "@/lib/entities/bindings/Job";
import type { MetricSnapshot } from "@/lib/entities/bindings/MetricSnapshot";
import type { MatchingModel } from "@/lib/entities/bindings/MatchingModel";
import type { Org } from "@/lib/entities/bindings/Org";
import type { Schedule } from "@/lib/entities/bindings/Schedule";
import type { Webhook } from "@/lib/entities/bindings/Webhook";
import type { WebhookDelivery } from "@/lib/entities/bindings/WebhookDelivery";
import type { AdminOrgRow } from "@/lib/query/admin";
import type { ConfigVersionRow } from "@/lib/query/config";
import type { InsightRow } from "@/lib/query/insights";
import type { ReceiptRow } from "@/components/sources/sources-content";
import type { JobRow, LineageRow } from "@/lib/query/hooks";
import type { ModelVersionDetail, ModelVersionRow } from "@/lib/query/models";
import type { ScheduleRow } from "@/lib/query/steward";
import type { WebhookDeliveryRow, WebhookRow } from "@/lib/query/webhooks";

/**
 * `true` when every key of `Ui` is either a field of `Entity` or a declared
 * `Composed` name; otherwise an object type whose single property names the
 * undeclared keys, so the compiler error reads:
 *
 *   Type 'boolean' is not assignable to type
 *   '{ UNDECLARED_WIRE_FIELDS: "progress" }'
 *
 * The `[…] extends [never]` tuple wrapper matters: a bare `extends never` on a
 * union distributes and silently succeeds for the empty case *and* for unions,
 * which would make the whole gate vacuous.
 */
type NoUndeclaredFields<Ui, Entity, Composed extends string = never> = [
  Exclude<keyof Ui, keyof Entity | Composed>,
] extends [never]
  ? true
  : { UNDECLARED_WIRE_FIELDS: Exclude<keyof Ui, keyof Entity | Composed> };

/**
 * One assertion per pair. A failure here is a compiler error, not a test
 * failure — the `it()` blocks below exist to keep the table from being deleted
 * as unused and to assert the properties the type system cannot.
 */
const PAIRS = {
  /**
   * `progress` is declared and sent by nothing. It stays listed rather than
   * deleted because the Stages card and its empty state are one dispatcher-side
   * producer away from working, and the field is now optional and guarded at
   * every read — but it is listed HERE, in the open, instead of looking like
   * part of the job contract. Delete it from `JobRow` when either a producer
   * lands (then it becomes a real `Job` field) or the card goes.
   */
  job: true satisfies NoUndeclaredFields<JobRow, Job, "progress">,

  /**
   * Three BFF-composed fields, all from `src/app/api/admin/orgs/route.ts`:
   * `display_name` and `registered` come from the erweb tenant registry (a
   * different database than er-server's control plane), `has_credentials` from
   * the credential vault. er-server knows about none of them, correctly.
   */
  adminOrg: true satisfies NoUndeclaredFields<
    AdminOrgRow,
    Org,
    "display_name" | "registered" | "has_credentials"
  >,

  modelVersion: true satisfies NoUndeclaredFields<ModelVersionRow, MatchingModel>,

  /**
   * `weights` is DERIVED, not stored: `model_weights` parses the settings
   * document and reports each comparison level's m/u and the `log2(m/u)` it
   * implies. The entity has no such column and should not — it is a view over
   * `model_json`, which the entity does have.
   */
  modelVersionDetail: true satisfies NoUndeclaredFields<
    ModelVersionDetail,
    MatchingModel,
    "weights"
  >,

  /**
   * The delivery receipt. `ingest_batch` had `languages: [rust]` and no `wire:`
   * until E9b, so no binding existed and this interface had nothing to be
   * checked against — even though the panel has rendered the receipt since the
   * read API shipped. Declaring the wire it was already on is what brought it
   * under the gate.
   */
  receipt: true satisfies NoUndeclaredFields<ReceiptRow, IngestBatch>,

  /**
   * The subscription as the index lists it — four fields, and deliberately not
   * the fifth: `webhooks_index` never projects `secret`, so a UI type that
   * carried it would state a contract the server refuses on purpose. The gate
   * cannot catch an omission, only an invention, which is why that reasoning is
   * written here rather than relied on.
   */
  /**
   * The two rates are DERIVED on read, not stored: `read::insights` computes
   * `duplicate_records / records` and `records / entities` and sends null
   * rather than 0.0 for an empty corpus. The entity has no such columns and
   * should not — they are a view over two it does have.
   */
  insight: true satisfies NoUndeclaredFields<
    InsightRow,
    MetricSnapshot,
    "duplicate_rate" | "records_per_entity"
  >,

  webhook: true satisfies NoUndeclaredFields<WebhookRow, Webhook>,

  webhookDelivery: true satisfies NoUndeclaredFields<WebhookDeliveryRow, WebhookDelivery>,

  configVersion: true satisfies NoUndeclaredFields<ConfigVersionRow, ConfigVersion>,
  lineage: true satisfies NoUndeclaredFields<LineageRow, GoldenLineage>,
  schedule: true satisfies NoUndeclaredFields<ScheduleRow, Schedule>,
} as const;

describe("wire contract: UI response shapes vs the generated entity bindings", () => {
  it("asserts every declared pair (a violation is a compile error, not this)", () => {
    // The assertions ARE the gate — each `satisfies` above is checked by `tsc`,
    // so there is nothing for a runtime expectation to add about their values
    // (eslint rightly rejects `=== true` on a `true`-typed expression). What is
    // worth asserting is the table itself: a pair quietly deleted to silence a
    // compiler error must fail here rather than shrink the gate in silence.
    expect(Object.keys(PAIRS).sort()).toEqual([
      "adminOrg",
      "configVersion",
      "insight",
      "job",
      "lineage",
      "modelVersion",
      "modelVersionDetail",
      "receipt",
      "schedule",
      "webhook",
      "webhookDelivery",
    ]);
  });

  it("proves the check is not vacuous", () => {
    // These mirror the two sides of `NoUndeclaredFields` on shapes whose answer
    // is known, which is what stops the gate from being a `true` that always
    // type-checks. The negative case is the one that matters: a field absent
    // from the entity must NOT resolve to `true`.
    type Entity = { a: string; b: number };
    type Clean = { a: string };
    type Dirty = { a: string; invented: boolean };

    const clean: NoUndeclaredFields<Clean, Entity> = true;
    expect(clean).not.toBeUndefined();

    // `invented` is not a field of Entity, so the assignment below must fail.
    // If the gate ever goes vacuous the directive becomes an unused
    // `@ts-expect-error`, which `tsc` reports as an error of its own (TS2578) —
    // so the proof cannot rot silently in either direction. Note the directive
    // has to be the LAST line of this comment: it suppresses the line
    // immediately following it, and with prose underneath it it suppressed a
    // comment line and reported itself unused. That is how this very assertion
    // caught its own first draft.
    // @ts-expect-error an invented field must not satisfy the entity contract
    const dirty: NoUndeclaredFields<Dirty, Entity> = true;
    expect(dirty).not.toBeUndefined();

    // ...and a declared composed field makes the same shape legal again.
    const composed: NoUndeclaredFields<Dirty, Entity, "invented"> = true;
    expect(composed).not.toBeUndefined();
  });
});
